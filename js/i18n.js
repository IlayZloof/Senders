export function readLang() {
  try {
    const stored = localStorage.getItem(LANG_KEY);
    if (stored === 'en' || stored === 'he') return stored;
  } catch {
    /* ignore */
  }
  return 'he';
}

export function isEnglish() {
  return readLang() === 'en';
}

export function dateLocale() {
  return isEnglish() ? 'en-GB' : 'he-IL';
}

export function applyDocumentLang(lang = readLang()) {
  const root = document.documentElement;
  const next = lang === 'en' ? 'en' : 'he';
  root.setAttribute('lang', next);
  root.setAttribute('dir', next === 'en' ? 'ltr' : 'rtl');
  root.setAttribute('data-lang', next);
}

export function setLang(lang) {
  const next = lang === 'en' ? 'en' : 'he';
  try {
    localStorage.setItem(LANG_KEY, next);
  } catch {
    /* ignore */
  }
  applyDocumentLang(next);
  window.location.reload();
}

export function t(key, vars) {
  const lang = readLang();
  let value = STRINGS[lang]?.[key] ?? STRINGS.he[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([name, val]) => {
      value = value.replaceAll(`{${name}}`, String(val ?? ''));
    });
  }
  return value;
}

export function regionLabel(region) {
  return t(`region.${region}`) === `region.${region}` ? (region || '') : t(`region.${region}`);
}

export function accessibilityLabel(value) {
  const key = `access.${value}`;
  const out = t(key);
  return out === key ? (value || t('common.unknown')) : out;
}

export function waterDepthLabel(value) {
  const raw = String(value || '').trim();
  const map = {
    עמוק: 'water.short.deep',
    בינוני: 'water.short.medium',
    רדוד: 'water.short.shallow',
    משתנה: 'water.short.varies',
    'לא ידוע': 'water.unknown',
    deep: 'water.short.deep',
    medium: 'water.short.medium',
    shallow: 'water.short.shallow',
    varies: 'water.short.varies',
    unknown: 'water.unknown',
  };
  const key = map[raw];
  return key ? t(key) : (raw || t('common.unknown'));
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (!key) return;
    if (el.tagName === 'TITLE') {
      document.title = t(key);
      el.textContent = t(key);
      return;
    }
    el.textContent = t(key);
  });
  root.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (key) el.innerHTML = t(key);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (key) el.setAttribute('placeholder', t(key));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const key = el.getAttribute('data-i18n-aria');
    if (key) el.setAttribute('aria-label', t(key));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    if (key) el.setAttribute('title', t(key));
  });
  const search = document.getElementById('mapSearch');
  if (search) search.setAttribute('dir', readLang() === 'en' ? 'ltr' : 'rtl');
  const desc = document.querySelector('meta[name="description"]');
  if (desc?.hasAttribute('data-i18n-content')) {
    desc.setAttribute('content', t(desc.getAttribute('data-i18n-content')));
  }
}

